import Foundation
import CryptoKit

/// v2rayA 自动下载安装器：从 GitHub Release 拉取最新版双二进制，
/// 校验 SHA-256，按标准布局写入用户指定目录，并生成 ctl 控制脚本。
enum V2rayaInstaller {

    struct Progress {
        var phase: String
        var detail: String = ""
    }

    static func installDir() -> String {
        V2rayAStore.installDir
    }

    static var isInstalled: Bool {
        let dir = installDir()
        return FileManager.default.isExecutableFile(atPath: dir + "/bin/v2raya")
            && FileManager.default.isExecutableFile(atPath: dir + "/bin/v2raya_core")
            && FileManager.default.fileExists(atPath: dir + "/v2raya-ctl")
    }

    // MARK: - Version
    /// 读取本地已安装的 v2raya 版本（执行 bin/v2raya --version）
    static func installedVersion() -> String? {
        let p = Process()
        p.executableURL = URL(fileURLWithPath: installDir() + "/bin/v2raya")
        p.arguments = ["--version"]
        let pipe = Pipe()
        p.standardOutput = pipe
        p.standardError = Pipe()
        do { try p.run() } catch { return nil }
        let data = pipe.fileHandleForReading.readDataToEndOfFile()
        p.waitUntilExit()
        guard let out = String(data: data, encoding: .utf8)?.trimmingCharacters(in: .whitespacesAndNewlines),
              !out.isEmpty else { return nil }
        return out.components(separatedBy: "\n").first
    }

    static func latestVersion() async throws -> String {
        let url = URL(string: "https://api.github.com/repos/v2rayA/v2rayA/releases/latest")!
        let (data, _) = try await URLSession.shared.data(from: url)
        if let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
           let tag = obj["tag_name"] as? String {
            return tag.hasPrefix("v") ? String(tag.dropFirst()) : tag
        }
        throw NSError(domain: "installer", code: 1,
                      userInfo: [NSLocalizedDescriptionKey: "无法解析最新版本号"])
    }

    // MARK: - Download
    private static func downloadToMemory(_ urlString: String, progress: @escaping (Int64, Int64) -> Void) async throws -> Data {
        guard let url = URL(string: urlString) else {
            throw NSError(domain: "installer", code: 2,
                          userInfo: [NSLocalizedDescriptionKey: "URL 无效: \(urlString)"])
        }
        let (stream, response) = try await URLSession.shared.bytes(from: url)
        let expected = (response as? HTTPURLResponse)?.expectedContentLength ?? -1
        var data = Data(); var received: Int64 = 0
        var buffer = [UInt8]()
        for try await b in stream {
            buffer.append(b); received += 1
            if buffer.count >= 1 << 20 {
                data.append(contentsOf: buffer); buffer.removeAll(keepingCapacity: true)
                progress(received, expected)
            }
        }
        data.append(contentsOf: buffer)
        progress(received, expected)
        return data
    }

    private static func sha256hex(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    // MARK: - ctl script template
    static func ctlScript(for dir: String) -> String {
        """
        #!/bin/sh
        # v2rayA (lite mode, per-user) controller — generated by V2raya Control
        set -eu
        BASE="\(dir)"
        BIN="$BASE/bin/v2raya"
        CORE="$BASE/bin/v2raya_core"
        CONF="$BASE/config"
        ASSETS="$BASE/assets"
        LOGDIR="$BASE/logs"
        LOGFILE="$LOGDIR/v2raya.log"
        PIDFILE="$BASE/run/v2raya.pid"
        ADDR=${V2RAYA_ADDR:-127.0.0.1:2017}
        HOST=${ADDR%:*}
        PORT=${ADDR##*:}

        running() {
          [ -f "$PIDFILE" ] || return 1
          pid=$(cat "$PIDFILE" 2>/dev/null || true)
          [ -n "${pid:-}" ] && kill -0 "$pid" 2>/dev/null
        }

        cmd_start() {
          if running; then echo "already: http://$HOST:$PORT"; exit 0; fi
          mkdir -p "$CONF" "$ASSETS" "$LOGDIR" "$BASE/run"
          nohup "$BIN" --lite --address "$ADDR" --config "$CONF" \\
                --v2ray-bin "$CORE" --v2ray-assetsdir "$ASSETS" \\
                --log-file "$LOGFILE" >>"$LOGDIR/stdout.log" 2>&1 &
          echo $! >"$PIDFILE"
          i=0
          while [ "$i" -lt 120 ]; do
            kill -0 "$(cat "$PIDFILE")" 2>/dev/null || { tail -n 20 "$LOGFILE" >&2; exit 1; }
            curl -fsS -o /dev/null -m 2 "http://$HOST:$PORT/" 2>/dev/null && { echo "ready: http://$HOST:$PORT"; exit 0; }
            sleep 1; i=$((i+1))
          done
          echo "not ready; see $LOGFILE" >&2; exit 1
        }

        cmd_stop() {
          if running; then
            pid=$(cat "$PIDFILE"); kill "$pid" 2>/dev/null || true
            i=0
            while kill -0 "$pid" 2>/dev/null && [ "$i" -lt 10 ]; do sleep 1; i=$((i+1)); done
            kill -9 "$pid" 2>/dev/null || true
            echo "stopped"
          else
            echo "not running"
          fi
          rm -f "$PIDFILE"
        }

        case "${1:-}" in
          start) cmd_start ;;
          stop) cmd_stop ;;
          restart) cmd_stop; cmd_start ;;
          status)
            if running; then echo "running: pid $(cat "$PIDFILE"), http://$HOST:$PORT"; exit 0
            else echo "stopped"; exit 1; fi ;;
          log) tail -n 50 -f "$LOGFILE" ;;
          *) echo "usage: $0 {start|stop|restart|status|log}" >&2; exit 2 ;;
        esac
        """
    }

    // MARK: - Install
    static func install(progress: @escaping @Sendable (Progress) -> Void,
                        version overrideVersion: String? = nil) async throws {
        let fm = FileManager.default
        let dir = installDir()
        let arch = "arm64"

        let version: String
        if let overrideVersion {
            version = overrideVersion
        } else {
            progress(Progress(phase: "查询最新版本"))
            version = try await latestVersion()
        }

        let base = "https://github.com/v2rayA/v2rayA/releases/download/v\(version)"
        let files: [(name: String, dest: String)] = [
            ("v2raya_darwin_\(arch)_\(version)", dir + "/bin/v2raya"),
            ("v2raya_core_darwin_\(arch)_\(version)", dir + "/bin/v2raya_core"),
        ]

        for (name, dest) in files {
            progress(Progress(phase: "下载 \(name)", detail: "v\(version)"))
            let data = try await downloadToMemory("\(base)/\(name)") { rec, total in
                if total > 0 {
                    let mb = Double(rec) / 1_048_576
                    let tot = Double(total) / 1_048_576
                    progress(Progress(phase: "下载 \(name)",
                                      detail: String(format: "%.1f / %.1f MB", mb, tot)))
                }
            }
            // 校验
            progress(Progress(phase: "校验 \(name)"))
            let shaUrl = "\(base)/\(name).sha256.txt"
            let (shaData, _) = try await URLSession.shared.data(from: URL(string: shaUrl)!)
            let expected = String(data: shaData, encoding: .utf8)?
                .trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
            let actual = sha256hex(data)
            guard expected.caseInsensitiveCompare(actual) == .orderedSame else {
                throw NSError(domain: "installer", code: 3, userInfo: [
                    NSLocalizedDescriptionKey: "SHA-256 校验失败 \(name)：期望 \(expected.prefix(16))… 实际 \(actual.prefix(16))…"
                ])
            }

            try fm.createDirectory(atPath: (dest as NSString).deletingLastPathComponent,
                                   withIntermediateDirectories: true)
            try data.write(to: URL(fileURLWithPath: dest), options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: dest)
        }

        // 目录布局
        progress(Progress(phase: "创建目录布局"))
        for sub in ["config", "assets", "logs", "run"] {
            try fm.createDirectory(atPath: dir + "/\(sub)", withIntermediateDirectories: true)
        }

        // ctl 脚本
        progress(Progress(phase: "写入控制脚本"))
        let ctl = dir + "/v2raya-ctl"
        try ctlScript(for: dir).write(toFile: ctl, atomically: true, encoding: .utf8)
        try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: ctl)

        // 去除隔离属性（GitHub 下载内容 macOS 会打标）
        progress(Progress(phase: "清理隔离标记"))
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/usr/bin/xattr")
        p.arguments = ["-cr", dir]
        try? p.run(); p.waitUntilExit()

        progress(Progress(phase: "完成", detail: "v\(version) 已安装到 \(dir)"))
    }
}
